import java.io.IOException;
import javax.servlet.RequestDispatcher;
import javax.servlet.ServletException;
import javax.servlet.annotation.WebServlet;
import javax.servlet.http.HttpServlet;
import javax.servlet.http.HttpServletRequest;
import javax.servlet.http.HttpServletResponse;

@WebServlet("/validate-password")
public class PasswordValidationServlet extends HttpServlet {
    @Override protected void doPost(HttpServletRequest request, HttpServletResponse response)
            throws ServletException, IOException {
        String password = request.getParameter("password");
        if ("Servlet".equals(password)) {
            // The required successful path uses RequestDispatcher.forward.
            RequestDispatcher welcome = request.getRequestDispatcher("/welcome");
            welcome.forward(request, response);
        } else {
            response.setContentType("text/html;charset=UTF-8");
            // Include the same password form with an error, using a Servlet writer.
            // Including a static file switches Tomcat to getOutputStream(), so the
            // included page is generated by a Servlet to keep one response writer.
            RequestDispatcher form = request.getRequestDispatcher("/q3-error");
            form.include(request, response);
        }
    }
}
